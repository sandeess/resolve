// Builds worker.js: a Cloudflare Worker that serves index.html as the sortitouthq.com home page.
// Usage: node deploy/cloudflare/build-worker.mjs   then paste worker.js into the Worker editor.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const html = readFileSync(join(here, "index.html"), "utf8")
const worker = `// Generated by build-worker.mjs from index.html. Do not edit by hand.
const HTML = ${JSON.stringify(html)};

export default {
  async fetch(request) {
    const url = new URL(request.url);
    if (url.pathname !== "/" && url.pathname !== "/index.html") {
      return new Response("Not found", { status: 404, headers: { "content-type": "text/plain; charset=utf-8" } });
    }
    return new Response(HTML, {
      headers: {
        "content-type": "text/html; charset=utf-8",
        "cache-control": "public, max-age=300",
        "x-content-type-options": "nosniff",
        "referrer-policy": "strict-origin-when-cross-origin",
        "content-security-policy": "default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
        "strict-transport-security": "max-age=31536000"
      }
    });
  }
};
`
writeFileSync(join(here, "worker.js"), worker)
console.log("wrote worker.js,", worker.length, "bytes")
